export function translateDynamic(text: string, language: Language): string {
  if (messages[text]) return messages[text][language];
  const question = /^Question (\d+)(?: of (\d+))?$/.exec(text);
  if (question) {
    const word = messages.Question[language];
    return question[2] ? `${word} ${question[1]} / ${question[2]}` : `${word} ${question[1]}`;
  }
  const numbered = /^(Mock exam|Practice set) No\. (\d+)$|^(Mock exam|Practice set) (\d+)$/.exec(text);
  if (numbered) return `${messages[numbered[1] || numbered[3]][language]} №${numbered[2] || numbered[4]}`;
  const greeting = /^(Good morning|Good afternoon|Good evening), (.+)$/.exec(text);
  if (greeting) {
    const greetings: Record<string, Record<Language, string>> = {
      'Good morning': { uz: 'Xayrli tong', kaa: 'Qayırlı tań', ru: 'Доброе утро' },
      'Good afternoon': { uz: 'Xayrli kun', kaa: 'Qayırlı kún', ru: 'Добрый день' },
      'Good evening': { uz: 'Xayrli kech', kaa: 'Qayırlı kesh', ru: 'Добрый вечер' }
    };
    return `${greetings[greeting[1]][language]}, ${greeting[2]}`;
  }
  const count = /^(\d+) (questions?|attempts?|days?|hours?|minutes?|seconds?|points?|groups?|answered|flagged|left)$/.exec(text);
  if (count) return `${count[1]} ${terms[count[2]]?.[language] ?? count[2]}`;
  if (/^\d+ h(?: \d+ min)?$|^\d+ min$/.test(text)) return text.replace(' h', ` ${terms.hour[language]}`).replace(' min', ` ${terms.minute[language]}`);
  // Composite labels contain independently translated segments, such as "20 questions · 2 h 30 min".
  if (text.includes(' · ')) return text.split(' · ').map((piece) => translateDynamic(piece, language)).join(' · ');
  // Unknown values (including names and source material) pass through unchanged.
  return text;
}
